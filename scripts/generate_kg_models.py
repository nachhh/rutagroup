"""Ontology → dbt code generation. Run: make ontology  (then `make udl`).

Reads ontology/ruta_ontology.yml and renders two dbt models (a PROPERTY GRAPH stored as tables):
  dbt/ruta_udl/models/kg/kg_nodes.sql   (node_id, node_type, label, properties JSON)
  dbt/ruta_udl/models/kg/kg_edges.sql   (src_id, predicate, dst_id, src_type, dst_type, valid_from, valid_to)

Why generate instead of hand-writing SQL? The ontology is the single source of truth for MEANING: add a class or a
relation in YAML, re-run, and the graph follows. (dbt's Jinja can't read arbitrary files, so a tiny generator is
the pragmatic bridge; the generated files are committed so the dbt project builds without this step.)
Node ids are typed strings, e.g. 'customer:123', 'shipment:9', so ids from different classes never collide.
"""

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
ONTO = yaml.safe_load((ROOT / "ontology/ruta_ontology.yml").read_text())
OUT = ROOT / "dbt/ruta_udl/models/kg"
HEADER = "-- GENERATED by scripts/generate_kg_models.py from ontology/ruta_ontology.yml. Do not edit: edit the ontology.\n"


def nid(cls, expr):
    return f"concat('{cls.lower()}:', cast({expr} as string))"


def prop_expr(p):
    return p if " as " in p else f"{p} as {p}"


def nodes_sql():
    parts = []
    for cls, spec in ONTO["classes"].items():
        n = spec["nodes"]
        props = ", ".join(prop_expr(p) for p in n["properties"])
        props_json = f"to_json(struct({props}))" if props else "json '{}'"
        parts.append(
            f"select {nid(cls, n['id'])} as node_id, '{cls}' as node_type, cast({n['label']} as string) as label,\n"
            f"       {props_json} as properties\nfrom {n['from']}"
        )
    return (HEADER + "-- grain: 1 row per entity instance (node) of an ontology class.\n"
            "{{ config(cluster_by=['node_type']) }}\n\n" + "\nunion all\n".join(parts) + "\n")


def edges_sql():
    parts = []
    for r in ONTO["relations"]:
        e = r["edges"]
        vf = f"cast({e['valid_from']} as timestamp)" if e.get("valid_from") else "cast(null as timestamp)"
        vt = f"cast({e['valid_to']} as timestamp)" if e.get("valid_to") else "timestamp '9999-12-31'"
        parts.append(
            f"select {nid(r['subject'], e['subject_id'])} as src_id, '{r['predicate']}' as predicate, "
            f"{nid(r['object'], e['object_id'])} as dst_id,\n"
            f"       '{r['subject']}' as src_type, '{r['object']}' as dst_type, {vf} as valid_from, {vt} as valid_to\n"
            f"from {e['from']}"
        )
    return (HEADER + "-- grain: 1 row per relationship instance (edge) of an ontology relation. Temporal edges carry validity.\n"
            "{{ config(cluster_by=['predicate', 'src_id']) }}\n\n" + "\nunion all\n".join(parts) + "\n")


def yml():
    preds = sorted({r["predicate"] for r in ONTO["relations"]})
    types = sorted(ONTO["classes"])
    return f"""{HEADER.replace('--', '#')}version: 2
models:
  - name: kg_nodes
    description: "Knowledge-graph nodes (property graph). One row per instance of an ontology class."
    config:
      contract: {{enforced: true}}
    columns:
      - name: node_id
        data_type: string
        data_tests: [unique, not_null]
      - {{name: label, data_type: string}}
      - {{name: properties, data_type: json}}
      - name: node_type
        data_type: string
        data_tests:
          - accepted_values:
              arguments:
                values: {types}
  - name: kg_edges
    description: "Knowledge-graph edges. One row per relationship instance; temporal edges have valid_from/valid_to."
    config:
      contract: {{enforced: true}}
    columns:
      - {{name: src_type, data_type: string}}
      - {{name: dst_type, data_type: string}}
      - {{name: valid_from, data_type: timestamp}}
      - {{name: valid_to, data_type: timestamp}}
      - name: predicate
        data_type: string
        data_tests:
          - accepted_values:
              arguments:
                values: {preds}
      - name: src_id
        data_type: string
        data_tests:
          - not_null
          - relationships:
              arguments:
                to: ref('kg_nodes')
                field: node_id
      - name: dst_id
        data_type: string
        data_tests:
          - not_null
          - relationships:
              arguments:
                to: ref('kg_nodes')
                field: node_id
"""


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "kg_nodes.sql").write_text(nodes_sql())
    (OUT / "kg_edges.sql").write_text(edges_sql())
    (OUT / "_kg.yml").write_text(yml())
    print(f"generated kg_nodes ({len(ONTO['classes'])} classes), kg_edges ({len(ONTO['relations'])} relations)")
